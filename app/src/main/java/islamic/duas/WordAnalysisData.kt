    fun getAnalysis(phrase: String): WordAnalysis? {
        return analyses.find { it.phrase == phrase || it.transliteration.equals(phrase, ignoreCase = true) }
    }

    fun getAnalysesByCategory(category: String): List<WordAnalysis> =
        analyses.filter { it.category == category }

    fun getTotalAnalyses(): Int = analyses.size

    fun search(query: String): List<WordAnalysis> {
        val q = query.lowercase()
        return analyses.filter {
            it.phrase.lowercase().contains(q) ||
            it.transliteration.lowercase().contains(q) ||
            it.fullMeaning.contains(q)
        }
    }
