    fun getResponse(isSad: Boolean): String {
        val key = if (isSad) "sad" else "lonely"
        return responses[key]?.let { it[Random.nextInt(it.size)] }
            ?: "اللہ آپ کے ساتھ ہے"
    }

    fun getResponseByMood(mood: String): String {
        val key = when (mood.lowercase()) {
            "sad", "اداس" -> "sad"
            "lonely", "تنہا", "بے کسی" -> "lonely"
            "anxious", "پریشان" -> "anxious"
            "grateful", "شکر" -> "grateful"
            else -> "sad"
        }
        return responses[key]?.let { it[Random.nextInt(it.size)] }
            ?: "اللہ آپ کے ساتھ ہے"
    }

    fun getAvailableMoods(): Map<String, String> = mapOf(
        "sad" to "دل اداس ہے",
        "lonely" to "بے کسی محسوس ہو رہی ہے",
        "anxious" to "پریشان ہوں",
        "grateful" to "شکر محسوس کر رہی ہوں"
    )

    fun getKeywordMatch(text: String): String {
        val lower = text.lowercase()
        return when {
            lower.contains("اداس") || lower.contains("غم") || lower.contains("رونا") -> "sad"
            lower.contains("تنہا") || lower.contains("اکیلی") || lower.contains("بے کس") -> "lonely"
            lower.contains("پریشان") || lower.contains("فکر") || lower.contains("ڈر") -> "anxious"
            lower.contains("شکر") || lower.contains("خوش") || lower.contains("مبارک") -> "grateful"
            else -> "sad"
        }
    }
