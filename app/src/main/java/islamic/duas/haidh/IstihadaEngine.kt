package islamic.duas.haidh

object IstihadaEngine {

    data class Ruling(val title: String, val description: String)

    fun getRulings(type: IstihadaType): List<Ruling> = when (type) {
        IstihadaType.NONE -> emptyList()
        IstihadaType.QALILA -> listOf(
            Ruling("استحاضہ قلیلہ (حکم: نماز روزہ)",
                  "قلیلہ استحاضہ میں خون تھوڑا اور بے قاعدہ ہوتا ہے۔ اس حالت میں نماز پڑھی جائے گی اور روزہ رکھا جائے گا۔"),
            Ruling("وضو کا حکم",
                  "قلیلہ استحاضہ سے وضو نہیں ٹوٹتا۔ البتہ ہر نماز کے لیے نیا وضو کرنا مستحب ہے۔"),
            Ruling("نماز کا حکم",
                  "استحاضہ قلیلہ کی حالت میں نماز پڑھنا فرض ہے۔ نماز ترک نہیں کی جائے گی۔"),
            Ruling("روزہ کا حکم",
                  "رمضان کے روزے رکھنا فرض ہیں اور یہ روزے صحیح شمار ہوں گے۔"),
            Ruling("جماع کا حکم",
                  "استحاضہ قلیلہ میں جماع جائز ہے، البتہ بہتر ہے کہ احتیاط برتی جائے۔")
        )
        IstihadaType.MUTAWASITA -> listOf(
            Ruling("استحاضہ متوسطہ (حکم: نماز روزہ)",
                  "متوسطہ استحاضہ میں خون درمیانی مقدار میں آتا ہے۔ نماز اور روزہ دونوں فرض ہیں۔"),
            Ruling("وضو کا حکم",
                  "متوسطہ استحاضہ سے وضو نہیں ٹوٹتا۔ ہر نماز کے لیے وضو کرنا مستحب ہے۔"),
            Ruling("غسل کا حکم",
                  "عرف عام میں متوسطہ کے لیے ہر نماز کے لیے غسل واجب نہیں۔ البتہ اگر خون مسلسل آ رہا ہو تو صرف وضو کافی ہے۔"),
            Ruling("نماز کا حکم",
                  "نماز فرض ہے اور وقت پر ادا کی جائے گی۔ استحاضہ نماز سے معذوری نہیں ہے۔"),
            Ruling("روزہ کا حکم",
                  "روزے صحیح ہیں اور فرض ہیں۔ استحاضہ روزے کو باطل نہیں کرتا۔")
        )
        IstihadaType.KATHIRA -> listOf(
            Ruling("استحاضہ کثیرہ (حکم: نماز روزہ)",
                  "کثیرہ استحاضہ میں خون بہت زیادہ اور مسلسل آتا ہے۔ اس حالت میں بھی نماز اور روزہ فرض ہیں۔"),
            Ruling("وضو کا حکم",
                  "ہر نماز کے لیے ایک وضو کافی ہے۔ نماز کے بعد اگر خون نکلے تو وضو نہیں ٹوٹتا۔"),
            Ruling("غسل کا حکم",
                  "کثیرہ استحاضہ میں ہر نماز کے لیے غسل واجب نہیں۔ صرف ایک بار غسل کافی ہے جب تک خون بند نہ ہو۔"),
            Ruling("فرض نمازیں",
                  "پانچوں فرض نمازیں وقت پر پڑھنا فرض ہیں۔ نماز ترک کرنا جائز نہیں۔"),
            Ruling("روزہ اور دیگر عبادات",
                  "روزے فرض ہیں۔ قرآن پڑھنا، ذکر، اور دعا سب جائز ہیں۔"),
            Ruling("جماع کا حکم",
                  "جماع مکروہ ہے البتہ حرام نہیں۔ بہتر ہے کہ احتیاط برتی جائے۔")
        )
    }
}
